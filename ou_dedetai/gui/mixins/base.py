"""What the window's mixins share.

MainWindow (window.py) inherits every mixin, with GuiApp last, so at run time a mixin's
`self` is the window: a mixin uses the window's attributes and the other mixins' methods
as its own, without declaring them.

For type checking only, WindowBase is a GuiApp that lists what the mixins use from the
window and from each other, so mypy can check each mixin on its own. At run time it is an
empty class.
"""
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from concurrent.futures import ThreadPoolExecutor
    from typing import Callable, Optional

    from PySide6.QtCore import QTimer
    from PySide6.QtWidgets import QMenu, QPushButton, QToolButton, QWidget

    from ...logos import State
    from ..app import GuiApp
    from ..close_dialog import CloseLogosDialog
    from ..install_guide import InstallGuide
    from ..tray import TrayController
    from ..widgets import StatusGui
    from ..window import Signals

    class WindowBase(GuiApp):
        signals: Signals
        status_gui: StatusGui
        _poller: ThreadPoolExecutor
        _updates: dict[str, tuple[bool, str]]
        _plans: list[dict]
        _layouts: list[str]
        while_closed: list[QWidget]
        _tray: Optional[TrayController]
        _close_dialog: Optional[CloseLogosDialog]
        _wine_builds_known: bool
        _installing: bool
        _last_state: Optional[State]
        _polling: bool
        guide: InstallGuide
        monitor_timer: QTimer
        reading_card: QWidget
        p_desktop: QPushButton
        t_integrations: QPushButton
        s_update: QToolButton
        h_update: QToolButton

        # MainWindow (window.py)
        def _logos_open(self) -> bool: ...
        def _refresh_later(self, *_): ...
        def closed_only(self, widget): ...
        def open_full(self, page: int = ...) -> None: ...
        def refresh(self) -> None: ...
        def show_page(self, index: int) -> None: ...
        def show_view(self, view: int) -> None: ...

        # AkousousinMixin (mixins/akousousin.py)
        def _akousousin_row(self) -> QWidget: ...
        def _check_akousousin_update(self, updates: dict) -> None: ...
        def _show_akousousin(self) -> None: ...
        def update_akousousin(self) -> None: ...

        # InstallMixin (mixins/install.py)
        def _install_from_full(self) -> None: ...
        def _set_product(self, product: str) -> None: ...
        def run_install(self) -> None: ...
        def run_installer(self) -> None: ...

        # IntegrationsMixin (mixins/integrations.py)
        def _load_integrations(self) -> None: ...
        def _show_desktop_integrations(self) -> None: ...
        def install_integrations(self) -> None: ...
        def recreate_shortcuts(self) -> None: ...

        # LogosMixin (mixins/logos.py)
        def add_open_items(self, menu: QMenu) -> None: ...
        def open_link(self, url: Optional[str]) -> None: ...
        def run_logos(self) -> None: ...
        def stop_logos(self, on_closed: Optional[Callable[[], None]] = ...) -> None: ...

        # SettingsMixin (mixins/settings.py)
        def edit_config(self) -> None: ...
        def refresh_settings(self) -> None: ...

        # SimpleViewMixin (mixins/simple.py)
        def _run_button(self) -> QToolButton: ...

        # TroubleshootMixin (mixins/troubleshoot.py)
        def run_windows_program(self) -> None: ...
        def run_wine_tool(self, exe: str, args: Optional[list[str]] = ...) -> None: ...
        def run_winetricks(self) -> None: ...

        # UpdatesMixin (mixins/updates.py)
        def _check_updates(self) -> dict: ...
        def _update_menu(self) -> QMenu: ...
        def check_updates_now(self) -> None: ...
        def update_wine_config(self) -> None: ...

        # WineBuildsMixin (mixins/wine_builds.py)
        def _oinos(self) -> bool: ...
        def _wine_build_button(self) -> QPushButton: ...
        def _wine_label(self) -> str: ...

else:
    class WindowBase:
        """The base of every mixin (see above)."""
